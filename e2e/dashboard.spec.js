const {test,expect}=require('@playwright/test');
test('sample dashboard filters, requires confirmation, and preserves user decisions',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await page.getByRole('button',{name:'Explore the sample workspace'}).click();
 await expect(page.getByRole('heading',{name:'Regulatory dashboard'})).toBeVisible();
 await expect(page.locator('.update')).toHaveCount(6);
 await page.locator('#jurisdiction-filter').selectOption('California');await expect(page.locator('.update')).toHaveCount(1);
 await page.locator('#jurisdiction-filter').selectOption('All jurisdictions');
 await page.getByRole('button',{name:'Heat injury & illness prevention',exact:true}).click();
 await expect(page.locator('.warning')).toContainText('Interpretation needs expert review');
 await expect(page.getByRole('button',{name:'Accept interpretation'})).toBeDisabled();
 await expect(page.getByRole('button',{name:'Flag for expert review',exact:true})).toBeDisabled();
 await page.locator('#confirm-review').check();await page.getByRole('button',{name:'Accept interpretation'}).click();
 await expect(page.locator('#detail')).not.toBeVisible();await expect(page.locator('.update').first()).toContainText('Accepted by you');
 await page.reload();await page.getByRole('button',{name:'Explore the sample workspace'}).click();await expect(page.locator('.update').first()).toContainText('Accepted by you');
 await page.locator('#search').fill('respiratory');await expect(page.locator('.update')).toHaveCount(1);
 await page.getByRole('button',{name:'Respiratory protection program review',exact:true}).click();
 await expect(page.locator('#confirm-review')).not.toBeChecked();
 await expect(page.getByRole('button',{name:'Accept interpretation'})).toBeDisabled();
 await page.getByRole('button',{name:'Generate impact analysis (sample)'}).click();await expect(page.locator('#detail .spinner')).toBeVisible();
 await expect(page.locator('#detail')).toContainText('Sample analysis:');
 await expect(page.getByRole('button',{name:'Accept interpretation'})).toBeDisabled();
 await page.locator('#confirm-review').check();await page.getByRole('button',{name:'Flag for expert review',exact:true}).click();
 await expect(page.locator('.update')).toContainText('Flagged for review');
 await page.getByRole('button',{name:'Settings',exact:true}).click();await page.getByRole('button',{name:'Show empty state'}).click();
 await expect(page.getByRole('heading',{name:'Your first update is on its way'})).toBeVisible();
 await page.getByRole('button',{name:'Restore sample updates'}).click();await expect(page.locator('.update')).toHaveCount(6);
 await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:'artifacts/dashboard-desktop.png',fullPage:true});
 await page.locator('#mobile-account').click();await page.getByRole('button',{name:'Go to sign in'}).click();await expect(page.getByRole('heading',{name:'Welcome back'})).toBeVisible();
 expect(errors).toEqual([]);
});
test('mobile dashboard and dialog fit the viewport',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/');await page.getByRole('button',{name:'Explore the sample workspace'}).click();
 await expect(page.locator('.update')).toHaveCount(6);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 await page.getByRole('button',{name:'Heat injury & illness prevention',exact:true}).click();await expect(page.locator('#detail')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 await page.screenshot({path:'artifacts/dashboard-mobile.png',fullPage:true});
});
